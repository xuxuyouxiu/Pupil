/**
 * i18n（v1.0.0）—— 渲染进程与主进程共用
 * 用法：入口处 setLocale(detectLocale())（renderer）或 setLocale(app.getLocale()...)（main），
 * 组件内 t('key') 取当前语言文案；缺键回退中文。
 */
export type Locale = 'zh' | 'en'

let current: Locale = 'zh'

export function setLocale(l: string | undefined): void {
  current = (l ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function getLocale(): Locale {
  return current
}

/** renderer 入口：跟随系统语言 */
export function detectLocale(): Locale {
  try {
    return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  } catch {
    return 'zh'
  }
}

